const dicts: Record<string, Dict> = { en, "zh-Hant": zh };

function pick(): string {
  const saved = localStorage.getItem("gogo.lang");
  if (saved && dicts[saved]) return saved;
  const nav = navigator.language.toLowerCase();
  return nav.startsWith("zh") ? "zh-Hant" : "en";
}

let lang = pick();
document.documentElement.lang = lang;

export function t(key: keyof Dict, vars: Record<string, string | number> = {}): string {
  let s = dicts[lang][key] ?? en[key];
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function toggleLanguage(): void {
  lang = lang === "en" ? "zh-Hant" : "en";
  localStorage.setItem("gogo.lang", lang);
  location.reload();
}

export function currentLanguage(): string {
  return lang;
}
